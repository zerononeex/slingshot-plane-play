// Coins of the fly-through pieces (arcs, rings, hoop lines), at absolute distances.
// `floor(x, d)` is the floor height there.
export function setPieceCoins(pieces, floor) {
  const out = [];
  for (const p of pieces) {
    const base = floor(p.x, p.d) + p.y;
    if (p.kind === 'coinArc') {
      for (let i = 0; i < 14; i++) { const t = i / 13; out.push({ x: p.x + (p.sway ?? 0) * Math.sin(t * Math.PI), y: base + p.rise * Math.sin(t * Math.PI), d: p.d + t * p.len, piece: p.id }); }
    } else if (p.kind === 'coinRing') {
      for (let i = 0; i < 12; i++) { const a = (i / 12) * Math.PI * 2; out.push({ x: p.x + Math.cos(a) * p.r, y: base + Math.sin(a) * p.r, d: p.d, piece: p.id }); }
    } else if (p.kind === 'hoops') {
      for (let k = 0; k < p.n; k++) for (const dd of [-2, 0, 2]) out.push({ x: p.x + (k % 2 ? p.zig : -p.zig), y: base + (k % 2 ? 2 : 0), d: p.d + k * p.gap + dd, piece: p.id });
    }
  }
  return out;
}

// Every authored feature in [d0, d1): the set pieces plus the world's per-lap furniture occurrences
// (portals, tunnels, courses, bridges, arches, slots, rings, gates…) → [{ d, type }] sorted by d.
export function authoredFeatures(stage, d0, d1) {
  const out = [];
  for (const p of setPiecesFor(stage.id)) if (p.d >= d0 && p.d < d1) out.push({ d: p.d, type: p.kind === 'landmark' ? `landmark:${p.look}` : p.kind });
  const lapItems = [
    ...stage.caverns.map((c) => ({ d: c.mouth, type: 'tunnel' })),
    ...stage.pockets.map((p) => ({ d: p.portal.d, type: `pocket:${p.id}` })),
    ...stage.courses.map((c) => ({ d: c.gates[0].d, type: 'course' })),
    ...stage.bridges.map((b) => ({ d: b.d, type: 'bridge' })),
    ...stage.arches.map((a) => ({ d: a.d, type: 'arch' })),
    ...stage.archways.map((a) => ({ d: a.d, type: 'archway' })),
    ...stage.slots.map((s) => ({ d: s.d, type: 'slot' })),
    ...stage.loopRings.map((r) => ({ d: r.d, type: 'loopRing' })),
    ...stage.diveGates.map((g) => ({ d: g.d, type: 'diveGate' })),
    ...stage.speedGates.map((g) => ({ d: g.d, type: 'speedGate' })),
    ...stage.rings.map((r) => ({ d: r.d, type: 'ring' })),
    ...stage.bumpables.map((b) => ({ d: b.d, type: `bump:${b.type}` })),
  ];
  for (const b of tailBumpablesFor(stage.id)) if (b.d >= d0 && b.d < d1) out.push({ d: b.d, type: `bump:${b.type}` });
  const neon = neonRunFor(stage.id); // v1.2 Neon Void's walls, laser rows, sliding walls and slipstreams
  if (neon) for (const f of [...neon.obstacles, ...neon.lanes.map((l) => ({ d: l.d0, kind: 'lane' }))]) if (f.d >= d0 && f.d < d1) out.push({ d: f.d, type: `neon:${f.kind}` });
  const mega = megaRunFor(stage.id); // v1.5 a mega-stage's weave rows, tilt sectors, loop doors, shooters, wild flyers, thermals, wind lanes
  if (mega) for (const f of mega.features) if (f.d >= d0 && f.d < d1) out.push({ d: f.d, type: `mega:${f.kind}` });
  for (let L = Math.floor(d0 / stage.cycle); L * stage.cycle < d1; L++) for (const it of lapItems) { const d = L * stage.cycle + it.d; if (d >= d0 && d < d1) out.push({ d, type: it.type }); }
  return out.sort((a, b) => a.d - b.d);
}
